def sources_for(p):
    manifest=json.loads((ROOT/'research/source-manifest.json').read_text())['files']
    out=[]
    for s in p['sources']:
        key,item=s.split(':',1)
        if key=='page':
            m=json.loads((ROOT/f'research/pages/{item}.json').read_text())
            # Page caches are optional in clean builds; metadata is frozen below.
            out.append(dict(label=item,url=m['url'],retrieved_at=m['retrieved_at'],sha256=m['sha256']))
        else:
            m=next(x for x in manifest if x['key']==key and x['path']==item)
            out.append(dict(label=item,url=m['url'],retrieved_at=m['repository_retrieved_at'],sha256=m['sha256']))
    return out

