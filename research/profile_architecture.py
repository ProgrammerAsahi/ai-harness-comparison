def wrap(text, max_width=228, size=16):
    lines=[]
    for part in text.split('\n'):
        line='';width=0
        for c in part:
            w=size if unicodedata.east_asian_width(c) in 'WF' else size*.56
            if width+w>max_width and line:lines.append(line);line='';width=0
            line+=c;width+=w
        if line:lines.append(line)
    return lines


def render_diagram(key,p):
    """Orthogonal edges avoid node boxes; per-tool edge sets carry the semantics."""
    import heapq
    positions,default_edges=LAYOUTS[p['layout']]
    # Node geometry is shared for consistent type size, not shared architecture.
    boxes=[(40+310*c,100+170*r,260,100) for c,r in positions]
    width=960;height=max(y+h for x,y,w,h in boxes)+90
    occupied=set()
    for x,y,w,h in boxes:
        for gx in range((x-10)//10,(x+w+10)//10+1):
            for gy in range((y-10)//10,(y+h+10)//10+1):occupied.add((gx,gy))
    used={};used_ports={};edges=p.get('edges',EDGES.get(key,default_edges));paths=[]
    def ports(b):
        x,y,w,h=b
        return [port for delta in [0,-20,20] for port in [((x+w//2+delta,y),(0,-1)),((x+w,y+h//2+delta),(1,0)),((x+w//2+delta,y+h),(0,1)),((x,y+h//2+delta),(-1,0))]]
    def route(a,b):
        best=None
        pairs=sorted([(abs(pa[0][0]-pb[0][0])+abs(pa[0][1]-pb[0][1])+500*(used_ports.get(pa[0],0)+used_ports.get(pb[0],0)),pa,pb) for pa in ports(a) for pb in ports(b)],key=lambda v:v[0])
        for _,(sp,sd),(tp,td) in pairs[:12]:
            start=(sp[0]//10+sd[0]*2,sp[1]//10+sd[1]*2)
            end=(tp[0]//10+td[0]*2,tp[1]//10+td[1]*2)
            q=[(0,0,start,sd)];cost={(start,sd):0};prev={};finish=None
            while q:
                _,g,xy,d=heapq.heappop(q)
                if g!=cost.get((xy,d)):continue
                if xy==end:finish=(xy,d);break
                for nd in [(1,0),(-1,0),(0,1),(0,-1)]:
                    nxt=(xy[0]+nd[0],xy[1]+nd[1])
                    if nxt in occupied or not(1<=nxt[0]<=95 and 7<=nxt[1]<=(height-55)//10):continue
                    ng=g+1+(3 if nd!=d else 0)+used.get(nxt,0)*8
                    state=(nxt,nd)
                    if ng<cost.get(state,1e9):
                        cost[state]=ng;prev[state]=(xy,d)
                        heapq.heappush(q,(ng+abs(nxt[0]-end[0])+abs(nxt[1]-end[1]),ng,nxt,nd))
            if finish:
                score=cost[finish]+4+50*(used_ports.get(sp,0)+used_ports.get(tp,0))
                if best is None or score<best[0]:
                    chain=[];s=finish
                    while s in prev:chain.append(s[0]);s=prev[s]
                    chain.append(start);chain.reverse()
                    best=(score,[sp]+[(x*10,y*10) for x,y in chain]+[tp])
        assert best,(key,a,b)
        pts=best[1]
        for endpoint in [pts[0],pts[-1]]:used_ports[endpoint]=used_ports.get(endpoint,0)+1
        for x,y in pts[1:-1]:used[(x//10,y//10)]=used.get((x//10,y//10),0)+1
        simple=[pts[0]]
        for i in range(1,len(pts)-1):
            x,y=pts[i];px,py=simple[-1];nx,ny=pts[i+1]
            if (x==px==nx) or (y==py==ny):continue
            simple.append((x,y))
        simple.append(pts[-1]);return simple
    for a,b in edges:
        pts=route(boxes[a],boxes[b]);d='M'+' L'.join(f'{x} {y}' for x,y in pts)
        paths.append(f'<path class="edge-halo" d="{d}" fill="none" stroke="#f3f7f6" stroke-width="6"/>')
        paths.append(f'<path data-edge="{a+1}-{b+1}" d="{d}" fill="none" stroke="#508984" stroke-width="1.7" marker-end="url(#arrow)"/>')
    nodes=[]
    for i,((x,y,w,h),label) in enumerate(zip(boxes,p['nodes'])):
        lines=wrap(label);assert len(lines)<=4,(key,label,lines)
        nodes.append(f'<rect data-node="{i+1}" x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="'+('#dceee9' if i in [1,4] else '#ffffff')+'" stroke="#adc9bf"/>')
        base=y+h/2-(len(lines)-1)*12+6
        for j,line in enumerate(lines):nodes.append(f'<text x="{x+w/2}" y="{base+j*24}" font-size="16" text-anchor="middle" fill="#24453c">{html.escape(line)}</text>')
    title=html.escape(key.split('-')[0]+' · '+p['focus'])
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-label="{title}"><title>{title}</title><desc>本图为相邻正文所述的架构切面。箭头表示主要信息或控制交接；具体证据和省略范围见正文。</desc><defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0 0 L8 4 L0 8" fill="none" stroke="#508984" stroke-width="1.3"/></marker></defs><style>text{{font-family:system-ui,-apple-system,'PingFang SC','Microsoft YaHei',sans-serif}}</style><rect width="{width}" height="{height}" rx="16" fill="#f3f7f6"/><text x="40" y="38" font-size="20" font-weight="600" fill="#163d34">{title}</text><text x="40" y="66" font-size="14" fill="#60796f">深入一层 · 模块、交接与状态；配合图下的机制表阅读</text>{''.join(paths)}{''.join(nodes)}<text x="40" y="{height-30}" font-size="14" fill="#60796f">主路径经过裁剪；同色框仅用于突出阅读重点，不代表相同进程或权限。</text></svg>'''


